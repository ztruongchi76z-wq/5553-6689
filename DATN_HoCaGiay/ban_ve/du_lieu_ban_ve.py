def mat_cat(Zc):
    """Các điểm đặc trưng mặt cắt (giống tham_fem.MatCat)."""
    h = dict(HH)
    h['Zc'] = Zc
    h['xcd'], h['xcu'] = h['B'] / 2, -h['B'] / 2
    h['x_b1'] = h['xcd'] + h['m1d'] * (Zc - h['Zcd'])
    h['x_b2'] = h['x_b1'] + h['bcd']
    h['x_l1'] = h['x_b2'] + h['m2d'] * (h['Zcd'] - h['Z_ltr'])
    h['x_l2'] = h['x_l1'] + h['b_ltr']
    h['x_l3'] = h['x_l2'] + h['m_ltr_ngoai'] * (h['Z_ltr'] - h['Zday'])
    h['x_l0'] = h['x_l1'] - h['m_ltr_trong'] * (h['Z_ltr'] - h['Zday'])
    h['x_u1'] = h['xcu'] - h['m1u'] * (Zc - h['Zcu'])
    h['x_u2'] = h['x_u1'] - h['bcu']
    h['x_u3'] = h['x_u2'] - h['m2u'] * (h['Zcu'] - h['Zday'])
    h['Zok'] = Zc - 1.0
    h['dx_ok'] = h['t_ong_khoi'] * np.sqrt(2)
    h['x_ok_u_bot'] = 1.0 + (h['Zok'] - h['Zday'])
    h['x_ok_d_dem'] = 1.0 + h['dx_ok'] + (h['Zok'] - (h['Zday'] + h['t_dem']))
    h['x_dem_end'] = h['x_l1'] - h['m_ltr_trong'] * (h['Z_ltr'] - (h['Zday'] + h['t_dem']))
    hck = h['Zday'] - h['ck_den']
    h['ck'] = [(h['x_ck'] - h['b_ck'] / 2 - hck, h['Zday']), (h['x_ck'] - h['b_ck'] / 2, h['ck_den']),
               (h['x_ck'] + h['b_ck'] / 2, h['ck_den']), (h['x_ck'] + h['b_ck'] / 2 + hck, h['Zday'])]
    return h


def x_mai_tl(h, z):
    """x của mái thượng lưu tại cao độ z."""
    if z >= h['Zcu']:
        return h['xcu'] - h['m1u'] * (h['Zc'] - z)
    return h['x_u2'] - h['m2u'] * (h['Zcu'] - z)


