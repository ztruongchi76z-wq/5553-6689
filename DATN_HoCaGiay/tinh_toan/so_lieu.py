def w_from_f(z, f):
    """Tính lại dung tích từ diện tích bằng công thức hình chóp cụt:
    dW = dz/3 * (F1 + F2 + sqrt(F1*F2))   [km2*m = 10^6 m3]"""
    w = np.zeros_like(f)
    for i in range(1, len(z)):
        dz = z[i] - z[i - 1]
        w[i] = w[i - 1] + dz / 3.0 * (f[i - 1] + f[i] + np.sqrt(f[i - 1] * f[i]))
    return w


